function getSavedLanguage() {
  const saved = localStorage.getItem(LOOMYVA_LANG_KEY);
  return saved === "el" ? "el" : "en";
}

function t(key) {
  const lang = getSavedLanguage();
  return LOOMYVA_I18N[lang]?.[key] || LOOMYVA_I18N.en[key] || key;
}

function updateLanguageButtons(lang = getSavedLanguage()) {
  document.querySelectorAll("[data-language-option]").forEach((button) => {
    const isActive = button.dataset.languageOption === lang;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", isActive ? "true" : "false");
  });
}

function applyLanguage(lang = getSavedLanguage()) {
  const safeLang = lang === "el" ? "el" : "en";

  localStorage.setItem(LOOMYVA_LANG_KEY, safeLang);
  document.documentElement.lang = safeLang;
  document.documentElement.setAttribute("data-lang", safeLang);

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (key && LOOMYVA_I18N[safeLang]?.[key]) {
      node.textContent = t(key);
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (key && LOOMYVA_I18N[safeLang]?.[key]) {
      node.setAttribute("placeholder", t(key));
    }
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
    const key = node.dataset.i18nAriaLabel;
    if (key && LOOMYVA_I18N[safeLang]?.[key]) {
      node.setAttribute("aria-label", t(key));
    }
  });

  const page = typeof getPageName === "function" ? getPageName() : "home";
  document.title = page === "search"
    ? `Loomyva ${t("navSearch")}`
    : page === "profile"
      ? `Loomyva ${t("navProfile")}`
      : "Loomyva";

  updateLanguageButtons(safeLang);
}

function renderLanguageSwitcher() {
  return `
    <div class="sidebar-language-box">
      <div class="sidebar-theme-head">
        <span data-i18n="language">${t("language")}</span>
        <small data-i18n="chooseLanguage">${t("chooseLanguage")}</small>
      </div>

      <div class="theme-toggle-group language-toggle-group" role="group" aria-label="Choose language">
        <button class="theme-toggle-btn language-toggle-btn" type="button" data-language-option="en">
          <span>EN</span>
          <span data-i18n="english">${t("english")}</span>
        </button>

        <button class="theme-toggle-btn language-toggle-btn" type="button" data-language-option="el">
          <span>EL</span>
          <span data-i18n="greek">${t("greek")}</span>
        </button>
      </div>
    </div>
  `;
}

function setupLanguageSwitcher() {
  const sidebar = document.getElementById("appSidebar");
  const themeBox = document.querySelector(".sidebar-theme-box");

  if (sidebar && themeBox && !document.querySelector(".sidebar-language-box")) {
    themeBox.insertAdjacentHTML("afterend", renderLanguageSwitcher());
  }

  document.querySelectorAll("[data-language-option]").forEach((button) => {
    button.addEventListener("click", () => {
      applyLanguage(button.dataset.languageOption);
      window.dispatchEvent(new CustomEvent("loomyva:language-change"));
    });
  });

  applyLanguage(getSavedLanguage());
}
